"""Render README.md from the portfolio site's content.json.

The site (adacovsk/adacovsk.github.io, src/content.json) is the single source of
truth. Edit that file, not README.md; this script overwrites README.md.

    python3 render.py                 # fetch content.json from the site repo's main
    python3 render.py path/to/content.json
"""
import json
import sys
import urllib.request

SOURCE = "https://raw.githubusercontent.com/adacovsk/adacovsk.github.io/main/src/content.json"
SITE = "https://adacovsk.github.io"
SELF = "https://github.com/adacovsk"


def load(arg):
    if arg:
        with open(arg, encoding="utf-8") as f:
            return json.load(f)
    with urllib.request.urlopen(SOURCE, timeout=30) as r:
        return json.load(r)


def render(c):
    home, skills = c["home"], c["resume"]["skills"]
    # Projects with a summary are code projects; the rest (e.g. trading) stay on the site.
    projects = [p for p in c["projects"]["personal"] if p.get("summary")]
    links = [f"[Portfolio & résumé]({SITE})"] + [
        f"[{l['text']}]({l['url']})" for l in home["links"] if l["url"].rstrip("/") != SELF
    ]
    out = [
        "<!-- Generated by render.py from adacovsk.github.io/src/content.json. Edit that file, not this one. -->",
        f"### {home['name']}",
        "",
        f"*{home['tagline']}*",
        "",
        home["intro"],
        "",
        " · ".join(links),
        "",
        "**Toolbox**",
        "",
        "| | |",
        "|---|---|",
        *[f"| {k} | {', '.join(v)} |" for k, v in skills.items()],
        "",
    ]
    # A project without a public repo gets its full write-up here, since there is no
    # README to click through to; public repos get one line and a link.
    for p in [p for p in projects if not p.get("url")]:
        name = p["title"] + (" *(private)*" if p.get("private") else "")
        out += [f"**{name}** — {p['summary']}", ""]
        out += [f"- {b}" for b in p["bullets"] if not b.startswith("Technologies:")]
        out += [""]
    linked = [p for p in projects if p.get("url")]
    if linked:
        out += ["**Other projects**", ""]
        out += [f"- [**{p['title']}**]({p['url']}) — {p['summary']}" for p in linked]
        out += [""]
    return "\n".join(out)


if __name__ == "__main__":
    text = render(load(sys.argv[1] if len(sys.argv) > 1 else None))
    with open("README.md", "w", encoding="utf-8") as f:
        f.write(text)
